    private static readonly Dictionary<string, SettingDefinition> ByKey =
        All.ToDictionary(d => d.Key, StringComparer.Ordinal);

    /// <summary>
    /// A setting by key — including a field of a setup other than the main
    /// one (<c>github.s1a2b3c4d.appId</c>), which is its main field under its
    /// own key, without a default that only described the local stack.
    /// </summary>
    public static SettingDefinition? Find(string key)
    {
        if (ByKey.TryGetValue(key, out var def)) return def;
        if (Setups.ParseScoped(key) is not { } scoped || !ByKey.TryGetValue(scoped.FieldKey, out var field))
            return null;
        return field with { Key = key, Default = field.MainOnlyDefault ? null : field.Default };
    }

    /// <summary>The main key a key stands for: itself, or the field a setup's key is a copy of.</summary>
    public static string MainKey(string key) => Setups.ParseScoped(key)?.FieldKey ?? key;

    public static string EnvVarName(string key) =>
        "WP_" + key.Replace('.', '_').ToUpperInvariant();
}
