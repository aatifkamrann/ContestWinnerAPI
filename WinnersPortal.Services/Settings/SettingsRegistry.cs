/// <summary>A configurable value the portal knows about. Unknown keys are rejected everywhere.</summary>
/// <param name="HelpRequired">
/// True when this field costs money, breaks an integration, cannot be undone, or uses
/// domain jargon — see HelpRegistry's coverage rule. A required topic that is missing
/// fails the build, so this is what keeps documentation in step with the settings.
/// </param>
/// <param name="Choices">
/// The values this setting accepts, when it is a choice rather than free
/// text — the screen renders a dropdown and the service refuses anything
/// else, so a typo cannot quietly switch a feature off.
/// </param>
/// <param name="IsMultiline">
/// True when the value is a document rather than a line — the screen gives it a
/// text area. Never combined with IsSecret or IsBoolean, which render as a masked
/// one-line box and a switch; the registry tests hold that line.
/// </param>
/// <param name="MainOnlyDefault">
/// True when the default describes the bundled local stack — Mailpit on
/// localhost, MinIO on port 9000 — rather than a convention. The main setup
/// keeps it, as it always had; a setup added beside it starts blank, since
/// a second SMTP server that already answers to "localhost" would look
/// configured and be nothing of the kind.
/// </param>
/// <param name="Trimmed">
/// True when a space around the value can only be a paste's leftover — a
/// key, a bucket, an address. It is saved without it: an access key with a
/// trailing space is a different key, and the store says only that it has
/// never heard of it.
/// </param>
public sealed record SettingDefinition(
    string Key,
    string Group,
    string Label,
    bool IsSecret = false,
    string? Default = null,
    bool HelpRequired = false,
    bool IsBoolean = false,
    bool IsMultiline = false,
    IReadOnlyList<SettingChoice>? Choices = null,
    bool MainOnlyDefault = false,
    bool Trimmed = false);

/// <summary>One option of a choice setting: what is stored, and what the screen shows.</summary>
public sealed record SettingChoice(string Value, string Label);

